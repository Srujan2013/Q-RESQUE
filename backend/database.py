def rows(sql, params=()):
    with connect() as db:
        result = db.execute(_sql(sql), params).fetchall()
        return [dict(row) for row in result]


def one(sql, params=()):
    with connect() as db:
        row = db.execute(_sql(sql), params).fetchone()
        return dict(row) if row else None


def insert(sql, params=()):
    statement = sql.strip().rstrip(";")
    if _postgres():
        if "RETURNING" not in statement.upper():
            statement += " RETURNING id"

        with connect() as db:
            row = db.execute(_sql(statement), params).fetchone()
            return row["id"] if row else None

    with connect() as db:
        cursor = db.execute(statement, params)
        return cursor.lastrowid


def execute(sql, params=()):
    with connect() as db:
        db.execute(_sql(sql), params)
